import type {
  CircuitComponentAsset,
  ComponentPin,
  PinSide,
  SignalType,
} from "../types/circuit";

type PinSeed = [
  pinKey: string,
  label: string,
  signalType: SignalType,
  aliases?: string[],
  notes?: string,
];

const pin = (
  componentSlug: string,
  pinKey: string,
  label: string,
  signalType: SignalType,
  side: PinSide,
  x: number,
  y: number,
  sortOrder: number,
  aliases: string[] = [],
  notes: string | null = null,
): ComponentPin => ({
  componentSlug,
  pinKey,
  label,
  signalType,
  side,
  x,
  y,
  sortOrder,
  aliases,
  notes,
});

const rowPins = (
  componentSlug: string,
  side: PinSide,
  y: number,
  xValues: number[],
  seeds: PinSeed[],
  orderOffset = 0,
) =>
  seeds.map(([pinKey, label, signalType, aliases = [], notes], index) =>
    pin(componentSlug, pinKey, label, signalType, side, xValues[index], y, orderOffset + index, aliases, notes),
  );

